"""`chkpmcpeks deploy` -- the whole stack in one idempotent command.

  1. images      CodeBuild -> ECR, pinned by digest           (terraform/build)
  2. platform    VPC, EKS Auto Mode, Cognito, Pod Identity, ACM (terraform/platform)
  3. cluster     kubeconfig, namespace + Graviton NodePool, External Secrets, Reloader
  4. secrets     reuse chkp/<server>; placeholders only where none exist
  5. workloads   Helm: servers + agentgateway + agent + ingress + policies
  6. verify      ALB up, unauthenticated request refused, tools/list through the gateway

Every step converges, so re-running after a failure or an interrupted session
picks up where it stopped.
"""

from __future__ import annotations

import os
import sys
import time
from dataclasses import replace

import yaml

from . import build, config, creds, terraform, ui, verify
from .awsutil import caller_identity, log
from .kube import CHART, PLATFORM_MANIFEST
from .kube_auth import write_kubeconfig
from .stack import Stack, wait_https

ROOT = terraform.ROOT
VALUES_GENERATED = os.path.join(CHART, "values-generated.yaml")

STEPS = ["Preflight", "Images (CodeBuild -> ECR)", "Platform (Terraform)", "Cluster access",
         "Namespace + Graviton NodePool", "Add-ons (External Secrets, Reloader)", "Check Point secrets",
         "Workloads (Helm)", "Load balancer", "Verify"]


def generated_values(cfg, out, resource_url=""):
    """Terraform outputs -> Helm values (written to values-generated.yaml)."""
    return {
        "region": cfg.region,
        "secrets": {"prefix": out.get("secret_name_prefix", "chkp/"),
                    "provider": {"aws": {"service": "SecretsManager", "region": cfg.region}}},
        "servers": {s: {"enabled": s in cfg.servers} for s in config.SERVER_CATALOG},
        "auth": {"issuer": out["cognito_issuer"], "jwksUrl": out["cognito_jwks_url"],
                 "allowedClientIds": [out["external_client_id"], out["agent_client_id"]],
                 "requiredScope": out["cognito_scope"], "resourceUrl": resource_url},
        "agent": {"gatewayTokenUrl": out["cognito_token_url"],
                  "clientSecretName": out["agent_client_secret_name"],
                  "llmSecretName": out["llm_secret_name"]},
        "ingress": {"certificateArn": out["certificate_arn"], "inboundCidrs": out["alb_inbound_cidrs"],
                    "host": out.get("domain_name") or ""},
        "networkPolicy": {"vpcCidr": out["vpc_cidr"]},
    }


def write_values(doc):
    with open(VALUES_GENERATED, "w", encoding="utf-8") as fh:
        fh.write("# GENERATED by `chkpmcpeks deploy` from Terraform outputs. Do not edit.\n")
        yaml.safe_dump(doc, fh, sort_keys=True)


def helm_deploy(kube, cfg, timeout="15m"):
    args = ["upgrade", "--install", cfg.helm_release, CHART, "-n", cfg.namespace,
            "-f", build.VALUES_IMAGES, "-f", VALUES_GENERATED, "--wait", "--timeout", timeout]
    for extra in os.environ.get("CHKP_HELM_VALUES", "").split(os.pathsep):
        if extra:
            args += ["-f", extra]           # e.g. an LLM provider override file
    kube.helm(*args)


def _confirm(cfg, already):
    if already:
        return True
    msg = (f"\nThis creates billable AWS resources in {cfg.region}: an EKS cluster, Auto Mode nodes, a NAT\n"
           "gateway and an ALB (about USD 10-12 per day while running; `chkpmcpeks destroy` removes it all).\n")
    if not sys.stdin.isatty():
        log(msg + "Non-interactive shell: re-run with --yes to proceed.")
        return False
    log(msg)
    try:
        return input("Proceed? [y/N] ").strip().lower() in ("y", "yes")
    except EOFError:
        return False


def run(cfg, session, args, profile=None):
    servers = config.parse_servers(args.servers) or cfg.servers
    cfg = replace(cfg, servers=tuple(servers))
    cfg.validate()
    st = Stack(cfg, session, profile)
    if not (args.yes or _confirm(cfg, st.deployed)):
        return 1

    rep = ui.Reporter("deploy", STEPS, context=f"{cfg.region} · {len(servers)} servers · {cfg.cluster_name}")
    try:
        rc, summary = _deploy(cfg, session, args, profile, rep)
    except Exception as e:
        rep.fail()
        rep.close(False, [f"  {type(e).__name__}: {e}",
                          "  Re-running `chkpmcpeks deploy` is safe: every step converges."])
        return 1
    rep.close(rc == 0, summary)
    return rc


def _deploy(cfg, session, args, profile, rep):
    from . import tools

    rep.begin("Preflight")
    ident = caller_identity(session, cfg.region)
    for t in ("terraform", "helm", "kubectl"):
        tools.require(t)
    log(f"  {ident['Arn']}  ·  servers: {' '.join(cfg.servers)}")

    rep.begin("Images (CodeBuild -> ECR)")
    if args.skip_build and os.path.exists(build.VALUES_IMAGES):
        log("  --skip-build: using the digests in values-images.yaml")
    else:
        build.build_images(cfg, session, profile, servers=cfg.servers, rep=_SubReporter(rep))

    rep.begin("Platform (Terraform)")
    log("  VPC, EKS Auto Mode, Cognito, Pod Identity roles, ACM -- first run takes ~15-20 min")
    terraform.apply("platform", cfg, profile)
    st = Stack(cfg, session, profile)
    out = st.out

    rep.begin("Cluster access")
    path = write_kubeconfig(session, cfg.region, out["cluster_name"], profile=profile)
    kube = st.kube
    log(f"  kubeconfig: {path}")
    if not kube.wait_api():
        raise RuntimeError("the Kubernetes API did not become reachable")

    rep.begin("Namespace + Graviton NodePool")
    kube.apply_file(PLATFORM_MANIFEST)

    rep.begin("Add-ons (External Secrets, Reloader)")
    kube.install_addon("external-secrets")
    kube.wait_crd("externalsecrets.external-secrets.io")
    kube.install_addon("reloader")

    rep.begin("Check Point secrets")
    made = creds.ensure_placeholders(cfg, session, cfg.servers)
    have = [s for s in cfg.servers_with_creds() if s not in made]
    log(f"  reusing {len(have)} existing chkp/<server> secret(s); placeholders created: {', '.join(made) or 'none'}")
    if args.creds:
        creds.apply(cfg, session, args.creds, kube=None, llm_secret=out.get("llm_secret_name"))

    rep.begin("Workloads (Helm)")
    write_values(generated_values(cfg, out))
    helm_deploy(kube, cfg)

    rep.begin("Load balancer")
    host = ""
    for _ in range(60):
        host = out.get("domain_name") or kube.ingress_hostname(cfg.namespace)
        if host:
            break
        time.sleep(10)
    if not host:
        raise RuntimeError("the ALB was not provisioned within 10 minutes (kubectl describe ingress -n chkp-mcp)")
    base = f"https://{host}"
    log(f"  {base}")
    # Advertise the real public URL in the gateway's OAuth resource metadata.
    write_values(generated_values(cfg, out, resource_url=f"{base}/mcp"))
    helm_deploy(kube, cfg)
    log("  waiting for ALB targets to become healthy (DNS + target registration, 2-5 min)")
    if not wait_https(f"{base}/healthz", st.ssl_context(), attempts=60, delay=10, label="the ALB"):
        raise RuntimeError(f"{base}/healthz did not answer 200 within 10 minutes")

    rep.begin("Verify")
    ok, lines = verify.check(st)
    summary = [
        f"  MCP endpoint : {base}/mcp      (Cognito client-credentials, scope {out['cognito_scope']})",
        f"  Agent API    : {base}/v1/chat",
        f"  Client id    : {out['external_client_id']}   (secret: in Cognito, never printed)",
        f"  Egress IPs   : {', '.join(out.get('nat_public_ips') or [])}   (allow-list on management servers)",
        "  Ask          : python -m chkpmcpeks chat \"what is the reputation of https://example.com?\"",
        "  Credentials  : python -m chkpmcpeks creds template   then   creds apply",
        "  Status       : python -m chkpmcpeks status",
        "  Tear down    : python -m chkpmcpeks destroy",
    ] + lines
    return (0 if ok else 1), summary


class _SubReporter:
    """Lets build_images run inside deploy's reporter without opening a new one."""

    def __init__(self, rep):
        self.rep = rep

    def begin(self, label=None):
        log(f"  · {label}")

    def fail(self):
        pass

    def close(self, *_a, **_k):
        pass
