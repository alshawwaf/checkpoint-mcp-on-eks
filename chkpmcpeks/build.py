"""`chkpmcpeks build` -- container images on AWS CodeBuild (arm64) into ECR.

No local Docker needed: the CLI zips images/ and services/agent/, uploads the
bundle, starts the CodeBuild project from terraform/build, streams its log, and
finally resolves every image to its digest and writes
charts/checkpoint-mcp/values-images.yaml so Helm deploys by digest.

Tags are immutable and content-derived, so a rebuild is skipped whenever the
tag already exists:
  server images  <server>-<pinned npm version>   (one ECR repo, many tags)
  agent image    agent-<sha of services/agent>
"""

from __future__ import annotations

import hashlib
import io
import os
import time
import zipfile

import yaml

from . import terraform, ui
from .awsutil import BotoCoreError, ClientError, err_code, log

ROOT = terraform.ROOT
AGENT_DIR = os.path.join(ROOT, "services", "agent")
VALUES_IMAGES = os.path.join(ROOT, "charts", "checkpoint-mcp", "values-images.yaml")
_SKIP_DIRS = {"__pycache__", "tests", ".pytest_cache"}

STEPS = ["Build stack (ECR + CodeBuild)", "Plan images", "Upload source", "CodeBuild", "Resolve digests"]


def _walk(base):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in _SKIP_DIRS)
        for f in sorted(filenames):
            if not f.endswith((".pyc", ".log")):
                yield os.path.join(dirpath, f)


def agent_tag():
    """Content hash of the agent source -> immutable, reproducible tag."""
    h = hashlib.sha256()
    for path in _walk(AGENT_DIR):
        h.update(os.path.relpath(path, ROOT).replace("\\", "/").encode())
        with open(path, "rb") as fh:
            h.update(fh.read().replace(b"\r\n", b"\n"))
    return "agent-" + h.hexdigest()[:12]


def source_zip():
    """images/ + services/agent/ with LF line endings (shell scripts run on Linux)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for base in (os.path.join(ROOT, "images"), AGENT_DIR):
            for path in _walk(base):
                arc = os.path.relpath(path, ROOT).replace("\\", "/")
                with open(path, "rb") as fh:
                    data = fh.read()
                if arc.endswith((".sh", ".yml", ".yaml", "Dockerfile", ".py", ".txt")):
                    data = data.replace(b"\r\n", b"\n")
                info = zipfile.ZipInfo(arc, date_time=(2026, 1, 1, 0, 0, 0))
                info.external_attr = (0o755 if arc.endswith(".sh") else 0o644) << 16
                info.compress_type = zipfile.ZIP_DEFLATED
                zf.writestr(info, data)
    return buf.getvalue()


def _digest(ecr, repo, tag):
    try:
        res = ecr.describe_images(repositoryName=repo, imageIds=[{"imageTag": tag}])
        return res["imageDetails"][0]["imageDigest"]
    except (ClientError, BotoCoreError, IndexError, KeyError):
        return None


def _tail(logs, group, stream, token):
    """Print new CodeBuild log lines; returns the next forward token."""
    if not (group and stream):
        return token
    try:
        kw = {"logGroupName": group, "logStreamName": stream, "startFromHead": True}
        if token:
            kw["nextToken"] = token
        res = logs.get_log_events(**kw)
    except ClientError:
        return token
    for ev in res.get("events", []):
        line = ev["message"].rstrip()
        if line and not line.startswith("[Container]"):
            log(line)
    return res.get("nextForwardToken", token)


def write_values(registry, server_repo, agent_repo, servers, agent):
    doc = {"images": {"registry": registry, "servers": servers,
                      "agent": agent, "serverRepository": server_repo, "agentRepository": agent_repo}}
    os.makedirs(os.path.dirname(VALUES_IMAGES), exist_ok=True)
    with open(VALUES_IMAGES, "w", encoding="utf-8") as fh:
        fh.write("# GENERATED by `chkpmcpeks build` -- image digests for Helm. Do not edit.\n")
        yaml.safe_dump(doc, fh, sort_keys=True)
    return VALUES_IMAGES


def build_images(cfg, session, profile=None, servers=None, only=None, rep=None):
    """Ensure every needed image exists in ECR; return the values file path."""
    servers = list(servers or cfg.servers)
    own_rep = rep is None
    rep = rep or ui.Reporter("build", STEPS, context=f"{cfg.region} · {len(servers)} server image(s) + agent")

    rep.begin("Build stack (ECR + CodeBuild)")
    terraform.apply("build", cfg, profile)
    out = terraform.outputs("build", profile, cfg.prefix)
    registry, srepo, arepo = out["registry"], out["server_repository"], out["agent_repository"]
    ecr = session.client("ecr", region_name=cfg.region)

    rep.begin("Plan images")
    want = {} if only == "agent" else {s: cfg.image_tag(s) for s in servers}
    missing = [s for s, tag in want.items() if not _digest(ecr, srepo, tag)]
    atag = agent_tag()
    need_agent = only != "servers" and not _digest(ecr, arepo, atag)
    log(f"  server images: {len(want) - len(missing)} present, {len(missing)} to build"
        + (f" ({', '.join(missing)})" if missing else ""))
    log(f"  agent image {atag}: {'to build' if need_agent else 'present'}")

    if missing or need_agent:
        rep.begin("Upload source")
        bundle = source_zip()
        session.client("s3", region_name=cfg.region).put_object(
            Bucket=out["source_bucket"], Key="source.zip", Body=bundle)
        log(f"  uploaded {len(bundle) / 1024:.0f} KiB to s3://{out['source_bucket']}/source.zip")

        rep.begin("CodeBuild")
        cb = session.client("codebuild", region_name=cfg.region)
        logs = session.client("logs", region_name=cfg.region)
        env = [{"name": "SERVER_BUILDS", "value": " ".join(f"{s}={cfg.servers_version(s)}" for s in missing),
                "type": "PLAINTEXT"},
               {"name": "AGENT_TAG", "value": atag if need_agent else "", "type": "PLAINTEXT"}]
        env += [{"name": "ARGS_" + s.replace("-", "_"), "value": cfg.startup_args(s), "type": "PLAINTEXT"}
                for s in missing if cfg.startup_args(s)]
        for attempt in range(6):   # the role may still be propagating right after creation
            try:
                build_id = cb.start_build(projectName=out["codebuild_project"],
                                          environmentVariablesOverride=env)["build"]["id"]
                break
            except ClientError as e:
                if attempt == 5 or err_code(e) not in ("AccessDeniedException", "InvalidInputException"):
                    raise
                time.sleep(10)
        log(f"  {build_id}")
        token, status = None, "IN_PROGRESS"
        while status == "IN_PROGRESS":
            time.sleep(10)
            b = cb.batch_get_builds(ids=[build_id])["builds"][0]
            status = b["buildStatus"]
            lg = b.get("logs", {})
            token = _tail(logs, lg.get("groupName"), lg.get("streamName"), token)
        time.sleep(3)
        _tail(logs, lg.get("groupName"), lg.get("streamName"), token)
        if status != "SUCCEEDED":
            rep.fail()
            if own_rep:
                rep.close(False, [f"  CodeBuild ended {status}. Logs: CloudWatch {lg.get('groupName')}"])
            raise RuntimeError(f"CodeBuild ended {status}")
    else:
        rep.begin("Upload source")
        log("  nothing to build")
        rep.begin("CodeBuild")
        log("  skipped -- every image already in ECR")

    rep.begin("Resolve digests")
    resolved, agent = {}, None
    for s, tag in want.items():
        d = _digest(ecr, srepo, tag)
        if not d:
            raise RuntimeError(f"image {srepo}:{tag} missing after build")
        resolved[s] = {"tag": tag, "digest": d}
    if only != "servers":
        d = _digest(ecr, arepo, atag)
        agent = {"tag": atag, "digest": d}
    path = write_values(registry, srepo, arepo, resolved, agent)
    log(f"  wrote {os.path.relpath(path, ROOT)}")
    if own_rep:
        rep.close(True, [f"  {len(resolved)} server image(s) + agent pinned by digest in "
                         f"{os.path.relpath(path, ROOT)}"])
    return path


def run(cfg, session, args, profile=None):
    from .config import parse_servers

    servers = parse_servers(args.servers) or cfg.servers
    try:
        build_images(cfg, session, profile, servers=servers, only=args.only)
    except RuntimeError as e:
        log(f"build failed: {e}")
        return 1
    return 0
